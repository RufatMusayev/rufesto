const L = require('./aysel-lib')
;(async () => {
  const b = await L.launch()
  const { page, errors } = await L.phone(b, 'Aysel Məmmədova')
  const t0 = Date.now()
  await page.goto(L.CONSUMER + '/')
  await page.waitForSelector('.soc-feed-slot', { timeout: 30000 })
  L.log('first card ms', Date.now() - t0)
  await page.waitForTimeout(2000)
  await L.shot(page, '00-home-top')
  L.log(await page.evaluate(() => document.body.innerText.slice(0, 1500)))
  L.log('errors', errors)
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
