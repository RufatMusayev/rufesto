// Round 2, part 10: "Order this" buttons (Scan table QR / Reserve), join T2, cart after reload, call waiter -> staff bell, end session.
const L = require('./aysel-r2-lib')
;(async () => {
  const b = await L.launch()
  const mgr = await L.api('Səid Əhmədov')
  const tables = await mgr.get('tables?restaurant_id=eq.' + L.FINCAN + '&select=id,table_number&order=table_number')
  const codes = await mgr.get('table_access_codes?restaurant_id=eq.' + L.FINCAN + '&select=table_id,access_code')
  const code = codes.find(c => c.table_id === tables.find(t => t.table_number === 'T2').id).access_code
  const A = await L.phone(b, 'Aysel Məmmədova')
  await L.step('Order this -> Scan table QR / Reserve', async () => {
    await A.page.goto(L.CONSUMER + '/'); await A.page.waitForSelector('.soc-feed-slot article'); await A.page.waitForTimeout(1200)
    await A.page.getByRole('link', { name: 'Order this' }).first().click(); await A.page.waitForSelector('.sheet'); await A.page.waitForTimeout(1500)
    const btns = await A.page.evaluate(() => [...document.querySelectorAll('.sheet button, .sheet a')].map(b => (b.getAttribute('aria-label') || b.innerText || '').trim().slice(0, 30) + ' ' + Math.round(b.getBoundingClientRect().height)))
    L.log('sheet controls:', btns)
    await A.page.getByRole('button', { name: /Scan table QR/i }).or(A.page.getByRole('link', { name: /Scan table QR/i })).first().click(); await A.page.waitForTimeout(2000)
    await L.shot(A.page, '17-scan-sheet')
    L.log('after Scan table QR:', (await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 300), '| app alive:', await A.page.evaluate(() => !!document.querySelector('#root > *')))
    await A.page.keyboard.press('Escape'); await A.page.waitForTimeout(500)
    await A.page.goBack().catch(() => {}); await A.page.waitForTimeout(1200)
    await A.page.getByRole('link', { name: 'Order this' }).first().click(); await A.page.waitForSelector('.sheet'); await A.page.waitForTimeout(1200)
    await A.page.getByRole('button', { name: /Reserve a table/i }).or(A.page.getByRole('link', { name: /Reserve a table/i })).first().click(); await A.page.waitForTimeout(2200)
    L.log('after Reserve a table: url', A.page.url().replace(L.CONSUMER, ''))
    await L.shot(A.page, '17-reserve-landing')
  })
  await L.step('join T2, cart after reload', async () => {
    await A.page.goto(L.CONSUMER + '/t/' + code); await A.page.waitForTimeout(2200)
    await A.page.getByRole('button', { name: 'Join', exact: true }).click(); await A.page.waitForTimeout(2200)
    await A.page.goto(L.CONSUMER + '/restaurant/fincan-coffee'); await A.page.waitForTimeout(2500)
    const row = A.page.locator('.mn-row').filter({ hasText: 'Flat White' }).first()
    await row.scrollIntoViewIfNeeded(); await row.locator('.mn-add').click(); await A.page.waitForTimeout(900)
    L.log('fab before reload', JSON.stringify(await A.page.evaluate(() => document.querySelector('.cart-fab')?.innerText)))
    await A.page.reload(); await A.page.waitForTimeout(3000)
    L.log('fab after reload', JSON.stringify(await A.page.evaluate(() => document.querySelector('.cart-fab')?.innerText)))
  })
  await L.step('call waiter -> staff bell', async () => {
    const M = await L.desk(b, 'Səid Əhmədov')
    await M.page.goto(L.RESTO + '/'); await M.page.waitForTimeout(3000)
    const bell = () => M.page.evaluate(() => (document.querySelector('[aria-label*="otification" i]')?.getAttribute('aria-label')) || null)
    L.log('manager bell before:', await bell())
    await A.page.goto(L.CONSUMER + '/table'); await A.page.waitForTimeout(2200)
    await A.page.getByRole('button', { name: /Call waiter/i }).click(); await A.page.waitForTimeout(1000)
    await L.shot(A.page, '17-call-sheet')
    L.log('call sheet:', (await A.page.evaluate(() => (document.querySelector('.sheet')?.innerText || document.body.innerText).replace(/\n+/g, ' | ').slice(0, 300))))
    const reasons = A.page.locator('.sheet button').filter({ hasText: /./ })
    L.log('sheet buttons:', await reasons.evaluateAll(es => es.map(e => e.innerText.trim().replace(/\n+/g, ' ').slice(0, 30))))
    await A.page.locator('.sheet button').filter({ hasText: /Water|Bill|Help|Assistance|Other|Something/i }).first().click().catch(() => {})
    await A.page.waitForTimeout(800)
    await A.page.getByRole('button', { name: /Send|Call|Confirm/i }).last().click().catch(() => {}); await A.page.waitForTimeout(2500)
    const t0 = Date.now()
    for (let i = 0; i < 20; i++) { const v = await bell(); if (v && /\d/.test(v)) { L.log('manager bell after call:', v, '(', Date.now() - t0, 'ms of polling )'); break } await M.page.waitForTimeout(500) }
    await M.page.locator('[aria-label*="otification" i]').first().click(); await M.page.waitForTimeout(1200)
    L.log('panel top:', (await M.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').match(/Notifications \| Mark all read.*?TODAY \|(.{0,260})/)?.[1])
    await L.shot(M.page, '17-staff-bell-call')
    await M.ctx.close()
  })
  await L.step('end session', async () => {
    await A.page.goto(L.CONSUMER + '/table'); await A.page.waitForTimeout(2000)
    await A.page.getByRole('button', { name: 'End Session' }).click(); await A.page.waitForTimeout(1500)
    L.log('after End Session:', (await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 160))
  })
  L.log('errors', A.errors.filter(e => !/ERR_ABORTED/.test(e)))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
