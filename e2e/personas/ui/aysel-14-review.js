const L = require('./aysel-lib')
const step = async (n, fn) => { try { L.log('\n=== ' + n); await fn() } catch (e) { L.log('STEP FAILED', n, String(e.message).split('\n')[0]) } }
;(async () => {
  const b = await L.launch()
  const A = await L.phone(b, 'Aysel Məmmədova')
  const api = await L.api('Aysel Məmmədova')
  await A.page.goto(L.CONSUMER + '/profile'); await A.page.waitForTimeout(2000)
  await A.page.getByText('Visits', { exact: true }).first().click(); await A.page.waitForTimeout(1000)
  await A.page.getByText('Fincan Coffee').first().click(); await A.page.waitForURL(/receipt/); await A.page.waitForTimeout(1500)
  await step('rate the croissant', async () => {
    const stars = A.page.locator('button').filter({ hasText: /^[☆★]$/ })
    L.log('star buttons', await stars.count(), 'aria', JSON.stringify(await stars.nth(0).getAttribute('aria-label')), 'title', JSON.stringify(await stars.nth(0).getAttribute('title')))
    await stars.nth(9).scrollIntoViewIfNeeded()
    const box = await stars.nth(9).boundingBox(); L.log('star box', JSON.stringify(box))
    await L.shot(A.page, '14-review-before')
    await stars.nth(9).click(); await A.page.waitForTimeout(400)
    await A.page.locator('textarea').fill('Flaky outside, buttery and warm inside. Best croissant near Fountain Square, perfect with the flat white.')
    await L.shot(A.page, '14-review-filled')
    const t0 = Date.now()
    await A.page.getByRole('button', { name: 'Send review' }).click()
    await A.page.waitForTimeout(1800)
    L.log('send ms', Date.now() - t0)
    await L.shot(A.page, '14-review-sent')
    L.log('after:', (await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(-350))
    const rv = await api.get('reviews?select=rating,body,is_verified,dishes(name),created_at&user_id=eq.' + api.uid + '&order=created_at.desc&limit=3')
    L.log('reviews now:', JSON.stringify(rv).slice(0, 600))
  })
  L.log('errors', A.errors)
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
