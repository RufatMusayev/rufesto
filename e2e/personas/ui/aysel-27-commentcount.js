const L = require('./aysel-lib')
;(async () => {
  const b = await L.launch()
  const A = await L.phone(b, 'Aysel Məmmədova', { storage: { rufesto_home_tab: 'friends' } })
  const api = await L.api('Aysel Məmmədova')
  await A.page.goto(L.CONSUMER + '/'); await A.page.waitForSelector('.soc-feed article'); await A.page.waitForTimeout(1500)
  const card = () => A.page.locator('.soc-feed article').filter({ hasText: 'Flaky, buttery croissant' }).first()
  const state = async tag => L.log(tag, '| footer:', (await card().locator('.soc-viewall, a[aria-label="Comments"]').allInnerTexts()).join(' / ').replace(/\n+/g, ' '), '| card tail:', (await card().innerText()).replace(/\n+/g, ' ').slice(-70))
  await state('before')
  await card().locator('a[aria-label="Comments"]').click(); await A.page.waitForSelector('.soc-composer-input')
  await A.page.locator('.soc-composer-input').fill('Thanks girls, you must try it!')
  await A.page.getByRole('button', { name: 'Send' }).click(); await A.page.waitForTimeout(1500)
  L.log('post page shows:', (await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 320))
  await A.page.goBack(); await A.page.waitForTimeout(1800)
  await state('after back (no reload)')
  await A.page.reload(); await A.page.waitForSelector('.soc-feed article'); await A.page.waitForTimeout(1500)
  await state('after reload')
  // clean up: delete my test comment through the API so the world keeps its shape
  const rows = await api.get('comments?select=id,body,target_type&user_id=eq.' + api.uid + '&order=created_at.desc&limit=2')
  L.log('my newest comments:', JSON.stringify(rows).slice(0, 300))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
