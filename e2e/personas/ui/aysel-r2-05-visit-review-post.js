// Round 2, part 4: Profile > Visits vs receipt, review the Flat White from the receipt, photo post tagged Fincan (verified?), where it lands.
const L = require('./aysel-r2-lib')
const SP = 'C:/Users/musay/AppData/Local/Temp/claude/C--Users-musay-Desktop-claude/9308ea1d-0f9a-4965-b895-2223492297b4/scratchpad/aysel-photo/croissant.jpg'
const CAPTION = 'Second round at Fincan: flat white and a flaky croissant, still the best breakfast near Fountain Square ☕🥐'
;(async () => {
  const b = await L.launch()
  const A = await L.phone(b, 'Aysel Məmmədova')
  const api = await L.api('Aysel Məmmədova')
  await L.step('profile visits vs receipt', async () => {
    await A.page.goto(L.CONSUMER + '/profile'); await A.page.waitForTimeout(2500)
    L.log('profile tabs:', await A.page.evaluate(() => [...document.querySelectorAll('[role=tab], .pf-tabs button')].map(t => (t.innerText.trim() || t.getAttribute('aria-label')) + ' ' + Math.round(t.getBoundingClientRect().width) + 'x' + Math.round(t.getBoundingClientRect().height))))
    await L.shot(A.page, '05-profile')
    await A.page.getByRole('tab', { name: /Visits/ }).or(A.page.getByRole('button', { name: /Visits/ })).first().click(); await A.page.waitForTimeout(1500)
    L.log('first visit rows:', (await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').match(/Visits.*?(Fincan Coffee[^|]*\|[^|]*\|[^|]*)/)?.[1])
    await L.shot(A.page, '05-profile-visits')
    await A.page.getByText('Fincan Coffee').first().click(); await A.page.waitForURL(/receipt/); await A.page.waitForTimeout(1800)
    await L.shot(A.page, '05-receipt')
    L.log('receipt:', (await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 800))
  })
  await L.step('review the Flat White from the receipt', async () => {
    const stars = A.page.locator('button').filter({ has: A.page.locator('svg') }).filter({ hasText: /^$/ })
    const rate = A.page.locator('button[aria-label^="Rate Flat White"]')
    L.log('rating buttons for Flat White:', await rate.count())
    await rate.nth(4).scrollIntoViewIfNeeded()
    await L.shot(A.page, '05-review-before')
    await rate.nth(4).click(); await A.page.waitForTimeout(300)
    await A.page.locator('textarea').fill('Silky and strong, exactly how a flat white should be.')
    await L.shot(A.page, '05-review-filled')
    await A.page.getByRole('button', { name: 'Send review' }).click(); await A.page.waitForTimeout(1800)
    L.log('after send:', (await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(-200))
    await L.shot(A.page, '05-review-sent')
  })
  await L.step('compose the photo post', async () => {
    await A.page.goto(L.CONSUMER + '/'); await A.page.waitForSelector('.soc-feed-slot article'); await A.page.waitForTimeout(800)
    await A.page.getByRole('button', { name: /New post/i }).click(); await A.page.waitForURL(/post\/new/); await A.page.waitForTimeout(1200)
    await A.page.locator('input[type="file"]').first().setInputFiles(SP)
    await A.page.waitForSelector('.soc-photo-slot img', { timeout: 20000 })
    await A.page.locator('#soc-caption').fill(CAPTION)
    await A.page.getByPlaceholder(/restaurant/i).fill('Fincan'); await A.page.waitForTimeout(1500)
    await L.shot(A.page, '05-composer-picker')
    L.log('picker options:', await A.page.evaluate(() => [...document.querySelectorAll('[role=option]')].map(o => o.innerText.replace(/\n+/g, ' ')).slice(0, 4)))
    await A.page.getByRole('option', { name: /Fincan Coffee/ }).click(); await A.page.waitForTimeout(600)
    await L.shot(A.page, '05-composer-ready')
    L.log('composer extras (dish / visit link)?', await A.page.evaluate(() => [...document.querySelectorAll('label, .label, h2, h3')].map(e => e.innerText.trim()).filter(Boolean)))
    const t1 = Date.now()
    await A.page.getByRole('button', { name: 'Post', exact: true }).click()
    await A.page.waitForURL(L.CONSUMER + '/', { timeout: 30000 })
    L.log('post -> home ms', Date.now() - t1)
    await A.page.waitForTimeout(2500)
    L.log('landed tab:', await A.page.evaluate(() => document.querySelector('[role=tab][aria-selected=true]')?.innerText))
    const rows = await A.page.evaluate(() => [...document.querySelectorAll('.soc-feed article')].filter(a => a.offsetParent).slice(0, 4).map(a => [a.querySelector('.soc-post-name')?.innerText, a.querySelector('.soc-post-time')?.innerText, a.innerText.includes('Verified') ? 'VERIFIED' : 'unverified', (a.querySelector('.soc-caption, .soc-review-text')?.innerText || '').slice(0, 40)].join(' | ')))
    L.log('Friends top 4:', rows)
    await L.shot(A.page, '05-after-post')
    const db = await api.rpc('friends_feed', { p_exclude: [], p_limit: 4 })
    L.log('friends_feed api top:', JSON.stringify((db.items || []).map(i => [i.kind, i.created_at && i.created_at.slice(11, 19), i.is_verified])))
    // Home: own post excluded?
    await A.page.getByRole('tab', { name: 'Home', exact: true }).click(); await A.page.waitForTimeout(1800)
    L.log('own posts on Home (first screen cards):', await A.page.evaluate(() => [...document.querySelectorAll('.soc-feed-slot article')].filter(a => /Aysel/.test(a.querySelector('.soc-post-name')?.innerText || '')).length))
  })
  L.log('errors', A.errors.filter(e => !/ERR_ABORTED/.test(e)))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
