const L = require('./aysel-r3-lib')
const sleep = ms => new Promise(r => setTimeout(r, ms))
;(async () => {
  const b = await L.launch()
  const A = await L.phone(b, 'Aysel Məmmədova'); const page = A.page
  await page.goto(L.CONSUMER + '/explore'); await page.waitForSelector('.sr-row'); await sleep(2000)
  const f = page.getByPlaceholder(/Dishes, places, people/i)
  await f.fill('doner'); await sleep(1500)
  await f.fill('tiramisu'); await sleep(350)
  L.log('350 ms after typing "tiramisu":', (await page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 200))
  await L.shot(page, '30-stale-rows-tiramisu-350ms')
  await sleep(2500); L.log('after 2.8 s:', (await page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 200))
  await f.fill('sada ocagi'); await sleep(3000)
  L.log('"sada ocagi" after 3 s:', (await page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 200))
  await L.shot(page, '30-sada-ocagi')
  await f.fill('seda ocagi'); await sleep(2500)
  L.log('"seda ocagi" after 2.5 s:', (await page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 160))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
