#!/usr/bin/env node
// Writes a one-off SQL file that stores the push secrets in Supabase Vault, read from the env file made by
// scripts/push-keys.mjs. The database trigger on notifications reads them back from vault.decrypted_secrets
// (docs/V2-CONTRACT.md section 21.3):
//   push_webhook_secret  the shared secret sent in the x-push-secret header
//   project_url          https://<project-ref>.supabase.co
//
// The SQL file contains the secret: apply it, then delete it. This script never prints secret values.
//   node scripts/push-vault-sql.mjs [--env <push.env>] [--out <file.sql>] [--project-ref <ref> | --project-url <url>]
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

const DEFAULT_DIR = 'C:\\Users\\musay\\AppData\\Local\\Temp\\claude\\C--Users-musay-Desktop-claude\\9308ea1d-0f9a-4965-b895-2223492297b4\\scratchpad'
const DEFAULT_PROJECT_REF = 'qqwvtuckljwvwrvyrjbn' // preview project

const args = process.argv.slice(2)
const opt = name => {
  const i = args.indexOf(name)
  return i >= 0 ? args[i + 1] : undefined
}

const envPath = resolve(opt('--env') || join(DEFAULT_DIR, 'push.env'))
const outPath = resolve(opt('--out') || join(dirname(envPath), 'push-vault.sql'))
const projectUrl = (opt('--project-url') || `https://${opt('--project-ref') || DEFAULT_PROJECT_REF}.supabase.co`).replace(/\/+$/, '')

let text
try {
  text = readFileSync(envPath, 'utf8')
} catch {
  console.error(`Cannot read ${envPath}. Run scripts/push-keys.mjs first.`)
  process.exit(1)
}
const env = {}
for (const line of text.split(/\r?\n/)) {
  const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim())
  if (m) env[m[1]] = m[2]
}

const secret = env.PUSH_WEBHOOK_SECRET
// Values go into single-quoted SQL literals: allow only characters that need no escaping.
if (!secret || !/^[A-Za-z0-9_-]{32,}$/.test(secret)) {
  console.error('PUSH_WEBHOOK_SECRET is missing or has unexpected characters in the env file.')
  process.exit(1)
}
if (!/^https:\/\/[a-z0-9.-]+$/.test(projectUrl)) {
  console.error('Project URL must look like https://<ref>.supabase.co')
  process.exit(1)
}

const upsert = (name, value, description) => `
  select id into v_id from vault.secrets where name = '${name}';
  if v_id is null then
    perform vault.create_secret('${value}', '${name}', '${description}');
  else
    perform vault.update_secret(v_id, '${value}', '${name}', '${description}');
  end if;`

const sql = `-- Rufesto push: Vault secrets (generated by scripts/push-vault-sql.mjs).
-- CONTAINS A SECRET: apply it once, then delete this file.
create extension if not exists supabase_vault;

do $push$
declare v_id uuid;
begin${upsert('push_webhook_secret', secret, 'Shared secret of the send-push Edge Function (x-push-secret header)')}
${upsert('project_url', projectUrl, 'Project URL used by the notifications push trigger')}
end
$push$;
`

writeFileSync(outPath, sql, { mode: 0o600 })
console.log('written')
console.log(`  ${outPath}`)
console.log(`  project_url = ${projectUrl}`)
console.log('Apply it, then delete the file.')
