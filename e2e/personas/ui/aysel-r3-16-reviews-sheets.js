// Round 3, part 11: compact review rows (heights, "...more", replies sheet, restaurant reviews sheet, write-review sheet), Profile > Reviews, public profile.
const L = require('./aysel-r3-lib')
const sleep = ms => new Promise(r => setTimeout(r, ms))
const note = (k, v) => L.log('  >>', k, v)
;(async () => {
  const b = await L.launch()
  const A = await L.phone(b, 'Aysel Məmmədova')
  const page = A.page
  await L.step('row heights on Friends, Search and the dish sheet', async () => {
    await page.goto(L.CONSUMER + '/'); await page.waitForSelector('article'); await sleep(1200)
    await page.getByRole('tab', { name: 'Friends', exact: true }).click(); await sleep(1800)
    const hs = await page.evaluate(() => [...document.querySelectorAll('article')].filter(a => a.querySelector('.rv-name')).slice(0, 8).map(a => ({ h: Math.round(a.getBoundingClientRect().height), lines: Math.round((a.querySelector('.rv-body, .rv-text')?.getBoundingClientRect().height || 0) / 20), photo: !!a.querySelector('img:not(.ui-img-el)') })))
    note('Friends review cards (height, ~lines)', JSON.stringify(hs.map(x => x.h + 'px/' + x.lines + 'L')))
    await L.shot(page, '16-friends-reviews')
  })
  await L.step('replies sheet', async () => {
    const card = page.locator('article').filter({ has: page.locator('.rv-name') }).first()
    await card.scrollIntoViewIfNeeded()
    const reply = card.getByRole('button', { name: /repl/i }).first()
    note('reply control', (await reply.getAttribute('aria-label')) + ' ' + JSON.stringify(await reply.boundingBox()))
    await reply.click(); await page.waitForSelector('.bs-panel'); await sleep(1200)
    await L.shot(page, '16-replies-sheet')
    note('replies sheet', (await page.evaluate(() => document.querySelector('.bs-panel').innerText)).replace(/\n+/g, ' | ').slice(0, 300))
    note('composer pinned?', await page.evaluate(() => { const i = document.querySelector('.bs-panel input, .bs-panel textarea'); if (!i) return 'no input'; const r = i.getBoundingClientRect(); return 'input bottom ' + Math.round(r.bottom) + ' of ' + innerHeight }))
    await page.keyboard.press('Escape'); await sleep(700)
  })
  await L.step('restaurant reviews sheet (tap the reviews count)', async () => {
    await page.goto(L.CONSUMER + '/restaurant/bella-roma'); await sleep(3000)
    await page.getByText('reviews', { exact: true }).first().click().catch(async () => { await page.locator('button, a').filter({ hasText: /reviews/ }).first().click() }); await sleep(2000)
    await L.shot(page, '16-restaurant-reviews')
    note('sheet', (await page.evaluate(() => (document.querySelector('.bs-panel')?.innerText || '(no sheet)'))).replace(/\n+/g, ' | ').slice(0, 360))
    await page.keyboard.press('Escape'); await sleep(600)
  })
  await L.step('write a review sheet (dish she has not reviewed)', async () => {
    await page.goto(L.CONSUMER + '/restaurant/bella-roma?tab=menu&dish=80000001-0000-0000-0000-000000000009'); await page.waitForSelector('.bs-panel'); await sleep(1500)
    const write = page.locator('.bs-panel').getByRole('button', { name: /Write/i }).first()
    note('Write control', (await write.count()) ? JSON.stringify(await write.boundingBox()) : 'none')
    await write.click(); await sleep(1000)
    await L.shot(page, '16-write-review')
    note('write sheet', (await page.evaluate(() => [...document.querySelectorAll('.bs-panel')].map(p => p.innerText.replace(/\n+/g, ' | ').slice(0, 160)))))
    note('stacked sheets', await page.locator('.bs-panel').count())
    await page.keyboard.press('Escape'); await sleep(700)
    note('after one Esc: sheets left', await page.locator('.bs-panel').count())
    await page.keyboard.press('Escape'); await sleep(700)
  })
  await L.step('Profile > Reviews and a public profile', async () => {
    await page.goto(L.CONSUMER + '/profile'); await sleep(2200)
    await page.getByRole('tab', { name: /Reviews/ }).or(page.getByRole('button', { name: /Reviews/ })).first().click(); await sleep(1800)
    await L.shot(page, '16-profile-reviews')
    const hs = await page.evaluate(() => [...document.querySelectorAll('article, li')].filter(a => a.querySelector('.rv-name, .rv-dish')).slice(0, 5).map(a => Math.round(a.getBoundingClientRect().height)))
    note('profile review row heights', JSON.stringify(hs))
    note('profile reviews text', (await page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(150, 420))
    await page.goto(L.CONSUMER + '/friends'); await sleep(2200); await L.shot(page, '16-friends-page')
    note('friends page', (await page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 300))
  })
  await L.step('map page', async () => {
    await page.goto(L.CONSUMER + '/map'); await sleep(3500)
    await L.shot(page, '16-map')
    note('map controls', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('button, input')].filter(e => e.offsetParent).map(e => ((e.getAttribute('aria-label') || e.innerText || e.placeholder || '').trim().slice(0, 22)) + ' ' + Math.round(e.getBoundingClientRect().width) + 'x' + Math.round(e.getBoundingClientRect().height)).slice(0, 10))))
  })
  L.log('errors', A.errors.filter(e => !/ERR_ABORTED/.test(e)))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
