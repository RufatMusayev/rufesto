const L = require('./aysel-lib')
const step = async (n, fn) => { try { L.log('\n=== ' + n); await fn() } catch (e) { L.log('STEP FAILED', n, String(e.message).split('\n')[0]) } }
;(async () => {
  const b = await L.launch()
  const { page, errors } = await L.phone(b, 'Aysel Məmmədova')
  await page.goto(L.CONSUMER + '/restaurant/fincan-coffee'); await page.waitForTimeout(2500)
  const tile = name => page.locator('.ig-grid-tile').filter({ has: page.getByText(name, { exact: true }) })
  await step('add flat white (cart opens by itself)', async () => {
    await tile('Flat White').scrollIntoViewIfNeeded()
    await tile('Flat White').locator('button').click(); await page.waitForTimeout(800)
    L.log('sheet open right after tap on +:', await page.locator('.sheet').count())
    await page.getByRole('button', { name: 'Close' }).click(); await page.waitForTimeout(500)
  })
  await step('add butter croissant', async () => {
    await tile('Butter Croissant').scrollIntoViewIfNeeded()
    await tile('Butter Croissant').locator('button').click(); await page.waitForTimeout(800)
    L.log('sheet open:', await page.locator('.sheet').count())
    await L.shot(page, '09-cart-two-items')
    L.log((await page.evaluate(() => document.querySelector('.sheet')?.innerText || document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 500))
  })
  await step('place order', async () => {
    const place = page.getByRole('button', { name: /Place order/i })
    L.log('place btn:', await place.innerText())
    const t0 = Date.now()
    await place.click()
    await page.waitForSelector('.dn-placed-ref', { timeout: 20000 }).catch(() => L.log('no placed confirmation'))
    L.log('order placed ms', Date.now() - t0)
    await page.waitForTimeout(600)
    await L.shot(page, '09-placed')
    L.log((await page.evaluate(() => document.querySelector('.sheet')?.innerText || document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 500))
    await page.getByRole('button', { name: /Go to (my )?table|Go to Table/i }).click().catch(() => {})
    await page.waitForTimeout(1500)
    L.log('URL', page.url().replace(L.CONSUMER, ''))
    await L.shot(page, '09-table-after-order')
    L.log((await page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 900))
  })
  L.log('\nerrors', errors)
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
