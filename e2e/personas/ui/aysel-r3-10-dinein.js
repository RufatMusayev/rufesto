// Round 3, part 6: scan table T1 at Fincan (the venue is closed at this hour), seated menu, dish sheet "Add to order", cart sheet, order,
// kitchen "Ready" -> bell + inbox "New" with the new wording.
const L = require('./aysel-r3-lib')
const fs = require('fs')
const sleep = ms => new Promise(r => setTimeout(r, ms))
const T = process.argv[2] || 'T1'
;(async () => {
  const b = await L.launch()
  const mgr = await L.api('Səid Əhmədov')
  const tables = await mgr.get('tables?restaurant_id=eq.' + L.FINCAN + '&select=id,table_number,state&order=table_number')
  const codes = await mgr.get('table_access_codes?restaurant_id=eq.' + L.FINCAN + '&select=table_id,access_code')
  const tb = tables.find(t => t.table_number === T); const code = codes.find(c => c.table_id === tb.id).access_code
  L.log('table', T, tb.state)
  const A = await L.phone(b, 'Aysel Məmmədova')
  const page = A.page
  const t00 = Date.now(); const note = (k, v) => L.log('  >>', k, v, '@' + (Date.now() - t00) + 'ms')
  await L.step('scan + join (venue closed)', async () => {
    await page.goto(L.CONSUMER + '/t/' + code); await sleep(2500)
    await L.shot(page, '10-join-card')
    note('join card', (await page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 260))
    await page.getByRole('button', { name: 'Join', exact: true }).click(); await sleep(2500)
    await L.shot(page, '10-table-empty')
    note('table page', (await page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 300))
  })
  await L.step('seated menu: + on a row, then a dish sheet with "Add to order"', async () => {
    await page.goto(L.CONSUMER + '/restaurant/fincan-coffee'); await sleep(3000)
    note('tabs', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('[role=tab]')].map(t => t.innerText.trim() + ':' + t.getAttribute('aria-selected')))))
    const add = page.locator('.mn-add').first()
    note('+ button box', JSON.stringify(await add.boundingBox()))
    const row = n => page.locator('.mn-row').filter({ hasText: n }).first()
    await row('Flat White').scrollIntoViewIfNeeded()
    await row('Flat White').locator('.mn-add').click(); await sleep(900)
    note('toast', (await page.evaluate(() => [...document.querySelectorAll('[class*=toast i], [role=status]')].map(e => e.innerText.replace(/\n+/g, ' / ')).join(' | ')).slice(0, 120)))
    await L.shot(page, '10-after-first-add')
    await row('Butter Croissant').scrollIntoViewIfNeeded()
    const y0 = await page.evaluate(() => scrollY)
    await row('Butter Croissant').locator('.mn-row-btn').click(); await page.waitForSelector('.bs-panel'); await sleep(1200)
    await L.shot(page, '10-dish-sheet-seated')
    const cta = await page.evaluate(() => [...document.querySelectorAll('.bs-foot button, .bs-foot a')].map(e => e.innerText.trim()))
    note('seated dish sheet footer', JSON.stringify(cta) + ' | scrollY behind ' + y0 + ' -> ' + (await page.evaluate(() => scrollY)))
    const tCta = Date.now()
    await page.locator('.dds-cta').click()
    await page.waitForFunction(() => !document.querySelector('.bs-panel'), null, { timeout: 5000 }).catch(() => {})
    note('sheet closed after the CTA in ms', Date.now() - tCta)
    await sleep(500)
    note('fab', JSON.stringify(await page.evaluate(() => document.querySelector('.cart-fab')?.innerText)) + ' | scrollY after ' + (await page.evaluate(() => scrollY)))
    await L.shot(page, '10-after-add-to-order')
  })
  await L.step('cart sheet: drag handle, place order', async () => {
    await page.locator('.cart-fab').click({ force: true }); await page.waitForSelector('.bs-panel'); await sleep(1000)
    await L.shot(page, '10-cart-sheet')
    note('cart', (await page.evaluate(() => document.querySelector('.bs-panel')?.innerText || '')).replace(/\n+/g, ' | ').slice(0, 260))
    note('cart footer buttons', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('.bs-foot button')].map(e => e.innerText.trim() + ' ' + Math.round(e.getBoundingClientRect().height)))))
    await page.getByRole('button', { name: /Place order/i }).click()
    await page.waitForSelector('.dn-placed-ref', { timeout: 20000 }).catch(() => note('placed', 'NO confirmation'))
    note('order placed', (await page.evaluate(() => (document.querySelector('.bs-panel')?.innerText || '').replace(/\n+/g, ' | ').slice(0, 160))))
    await L.shot(page, '10-placed')
    await page.getByRole('button', { name: /Done/i }).click().catch(() => {}); await sleep(1500)
  })
  await page.goto(L.CONSUMER + '/'); await page.waitForSelector('article'); await sleep(1500)
  const bell = () => page.evaluate(() => { const e = document.querySelector('[aria-label*="otification" i]'); return e ? ((e.getAttribute('aria-label') || '') + '|' + (e.innerText || '').trim()) : null })
  note('bell before kitchen', await bell())
  const M = await L.desk(b, 'Səid Əhmədov')
  await L.step('kitchen: start + ready', async () => {
    await M.page.goto(L.RESTO + '/kds'); await M.page.waitForSelector('.kds-advance-btn', { timeout: 30000 })
    const btns = M.page.locator('.kds-advance-btn')
    for (let i = 0; i < 6 && await btns.filter({ hasText: /Start/i }).count(); i++) { await btns.filter({ hasText: /Start/i }).first().click(); await M.page.waitForTimeout(600) }
    await sleep(3000); note('bell after Preparing', await bell())
    const tReady = Date.now()
    for (let i = 0; i < 6 && await btns.filter({ hasText: /ready/i }).count(); i++) { await btns.filter({ hasText: /ready/i }).first().click(); await M.page.waitForTimeout(500) }
    let seen = null
    for (let i = 0; i < 40; i++) { const v = await bell(); if (v && /\|\d/.test(v)) { seen = Date.now() - tReady; note('bell shows', v + ' after ' + seen + 'ms since the Ready tap'); break } await sleep(400) }
    if (seen == null) note('bell', 'NO badge in 16 s')
  })
  await L.step('inbox', async () => {
    await page.locator('[aria-label*="otification" i]').first().click(); await page.waitForSelector('li.ntf-li'); await sleep(2200)
    await L.shot(page, '10-inbox-food-ready')
    note('sections', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('h2, h3')].map(e => e.innerText.trim()).filter(t => t.length < 20))))
    note('top rows', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('li.ntf-li')].slice(0, 3).map(li => Math.round(li.getBoundingClientRect().top) + '/' + Math.round(li.getBoundingClientRect().height) + ' ' + li.innerText.replace(/\n+/g, ' | ')))))
    note('bell after opening', await bell())
  })
  fs.writeFileSync(L.path.join(L.OUT, 'state.json'), JSON.stringify({ table: T, code }))
  L.log('errors A', A.errors.filter(e => !/ERR_ABORTED/.test(e)), 'M', M.errors)
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
