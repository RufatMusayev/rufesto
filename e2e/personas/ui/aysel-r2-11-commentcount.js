const L = require('./aysel-r2-lib')
;(async () => {
  const b = await L.launch()
  const A = await L.phone(b, 'Aysel Məmmədova', { storage: { rufesto_home_tab: 'friends' } })
  await A.page.goto(L.CONSUMER + '/'); await A.page.waitForSelector('.soc-feed article'); await A.page.waitForTimeout(1500)
  const card = () => A.page.locator('.soc-feed article').filter({ hasText: 'Second round at Fincan' }).first()
  const state = async tag => L.log(tag.padEnd(26), '| comment-link texts:', (await card().locator('.soc-viewall, a[aria-label="Comments"]').allInnerTexts()).join(' / ').replace(/\n+/g, ' '))
  await state('before')
  await card().locator('a[aria-label="Comments"]').click(); await A.page.waitForSelector('.soc-composer-input')
  await A.page.locator('.soc-composer-input').fill('Come at 9, it is quiet and the croissants are still warm!')
  await A.page.getByRole('button', { name: 'Send' }).click(); await A.page.waitForTimeout(1500)
  L.log('post page now:', (await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').match(/\| (\d+) \|\s*\d+ likes?/)?.[0])
  await A.page.goBack(); await A.page.waitForTimeout(1800)
  await state('after back (no reload)')
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
