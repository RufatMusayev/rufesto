const L = require('./aysel-lib')
;(async () => {
  const a = await L.api('Aysel Məmmədova')
  const r = await a.rpc('home_feed', { p_exclude: [], p_limit: 20 })
  L.log('mix', JSON.stringify(r.mix), 'radius', r.radius_km, 'caught_up', r.caught_up)
  r.items.forEach((it, i) => L.log(i, it.kind, 'why=' + JSON.stringify(it.why), 'pool=' + it.pool, 'km=' + it.km, 'pos=' + it.position, 'mine=' + it.is_mine, (it.author?.name || it.restaurant?.name || '') + ' | ' + (it.restaurant?.name || '') , it.created_at?.slice(0, 16), 'likes=' + it.like_count, 'liked=' + it.liked_by_me))
  const r2 = await a.rpc('home_feed', { p_exclude: r.items.map(i => i.id), p_limit: 20 })
  L.log('page2 caught_up', r2.caught_up, 'n', r2.items?.length)
  r2.items?.forEach((it, i) => L.log(i, it.kind, 'why=' + JSON.stringify(it.why), 'pool=' + it.pool, 'mine=' + it.is_mine, (it.author?.name || '') + ' | ' + (it.restaurant?.name || ''), it.created_at?.slice(0, 16)))
  const fr = await a.get('friendships?select=*&limit=50').catch(() => null)
  L.log('friendships sample', JSON.stringify(fr)?.slice(0, 300))
  const fol = await a.get('follows?select=restaurant_id,restaurants(name)&user_id=eq.' + a.uid)
  L.log('follows', JSON.stringify(fol))
})().catch(e => { console.error(e); process.exit(1) })
