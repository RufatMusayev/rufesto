const L = require('./aysel-r3-lib')
const sleep = ms => new Promise(r => setTimeout(r, ms))
;(async () => {
  const b = await L.launch()
  const api = await L.api('Aysel Məmmədova')
  const A = await L.phone(b, 'Aysel Məmmədova')
  const page = A.page
  await L.step('Delete Mehriban\'s request in the inbox', async () => {
    await page.goto(L.CONSUMER + '/notifications'); await page.waitForSelector('li.ntf-li'); await sleep(2500)
    L.log('sections:', await page.evaluate(() => [...document.querySelectorAll('h2, h3')].map(e => e.innerText.trim()).filter(t => t.length < 20)))
    const row = page.locator('li.ntf-li').filter({ hasText: 'Mehriban' }).filter({ hasText: 'friend request' }).first()
    L.log('row found:', await row.count(), '|', (await row.innerText().catch(() => '')).replace(/\n+/g, ' | '))
    const h0 = await row.evaluate(r => Math.round(r.getBoundingClientRect().height))
    const t0 = Date.now()
    await row.getByRole('button', { name: 'Delete' }).click(); await sleep(150)
    const hMid = await page.locator('li.ntf-li').filter({ hasText: 'Mehriban' }).filter({ hasText: 'friend request' }).first().evaluate(r => Math.round(r.getBoundingClientRect().height)).catch(() => 'gone')
    await sleep(800)
    L.log('Delete: height', h0, '->', hMid, '(150 ms) | still listed after 1 s:', await page.locator('li.ntf-li').filter({ hasText: 'Mehriban' }).filter({ hasText: 'friend request' }).count())
    await L.shot(page, '08b-after-delete')
    const rows = await api.get('friendships?select=status&requester_id=eq.' + (await L.api('Mehriban Rzayeva')).uid + '&addressee_id=eq.' + api.uid)
    L.log('friendship row Mehriban->Aysel after Delete:', JSON.stringify(rows))
  })
  await L.step('Mehriban sends again through the UI, with the network watched', async () => {
    const F = await L.phone(b, 'Mehriban Rzayeva')
    const calls = []
    F.page.on('response', async r => { if (/rpc\/send_friend_request/.test(r.url())) calls.push(r.status() + ' ' + (r.request().postData() || '') + ' -> ' + (await r.text().catch(() => '')).slice(0, 120)) })
    await F.page.goto(L.CONSUMER + '/explore'); await sleep(2500)
    await F.page.getByPlaceholder(/Dishes, places, people/i).fill('aysel'); await sleep(3000)
    const rowsBefore = await F.page.evaluate(() => [...document.querySelectorAll('[class*=sr-] button, button')].filter(b => /Add friend|Requested/.test(b.innerText)).map(b => b.closest('li, div')?.innerText.replace(/\n+/g, ' / ').slice(0, 50)))
    L.log('people rows:', rowsBefore)
    await F.page.getByRole('button', { name: /Add friend/i }).first().click(); await sleep(2500)
    L.log('send_friend_request calls:', calls)
    L.log('after click, rows:', await F.page.evaluate(() => [...document.querySelectorAll('button')].filter(b => /Add friend|Requested/.test(b.innerText)).map(b => (b.closest('li, div')?.innerText || '').replace(/\n+/g, ' / ').slice(0, 50))))
    await F.ctx.close()
  })
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
