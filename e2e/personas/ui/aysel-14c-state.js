const L = require('./aysel-lib')
;(async () => {
  const api = await L.api('Aysel Məmmədova')
  L.log('my_table_session', JSON.stringify(await api.rpc('my_table_session')))
  const b = await L.launch()
  const A = await L.phone(b, 'Aysel Məmmədova')
  await A.page.goto(L.CONSUMER + '/profile'); await A.page.waitForTimeout(2500)
  await A.page.getByText('Visits', { exact: true }).first().click(); await A.page.waitForTimeout(1200)
  const row = A.page.getByText('Fincan Coffee').first()
  L.log('row tag', await row.evaluate(e => e.closest('a,button,[role=button]')?.tagName || 'none'))
  await row.click(); await A.page.waitForTimeout(2000)
  L.log('URL', A.page.url().replace(L.CONSUMER, ''))
  await L.shot(A.page, '14-visit-click')
  L.log((await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 700))
  await A.page.goto(L.CONSUMER + '/table'); await A.page.waitForTimeout(2500)
  L.log('/table:', (await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 400))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
