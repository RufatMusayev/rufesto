const L = require('./aysel-lib')
const SP = 'C:/Users/musay/AppData/Local/Temp/claude/C--Users-musay-Desktop-claude/9308ea1d-0f9a-4965-b895-2223492297b4/scratchpad/aysel-photo/croissant.jpg'
const step = async (n, fn) => { try { L.log('\n=== ' + n); await fn() } catch (e) { L.log('STEP FAILED', n, String(e.message).split('\n')[0]) } }
;(async () => {
  const b = await L.launch()
  const A = await L.phone(b, 'Aysel Məmmədova')
  const api = await L.api('Aysel Məmmədova')
  await A.page.goto(L.CONSUMER + '/'); await A.page.waitForSelector('.soc-feed-slot'); await A.page.waitForTimeout(800)
  await step('open composer', async () => {
    const fab = A.page.getByRole('button', { name: 'New post' })
    L.log('fab box', JSON.stringify(await fab.boundingBox()))
    await fab.click(); await A.page.waitForTimeout(1500)
    L.log('URL', A.page.url().replace(L.CONSUMER, ''))
    await L.shot(A.page, '15-composer-empty')
  })
  await step('attach photo + caption + restaurant, post', async () => {
    const t0 = Date.now()
    await A.page.locator('input[type="file"]').first().setInputFiles(SP)
    await A.page.waitForSelector('.soc-photo-slot img', { timeout: 20000 })
    L.log('photo preview ms', Date.now() - t0)
    await A.page.locator('#soc-caption').fill('Flaky, buttery croissant at Fincan Coffee with a flat white. Perfect coffee break ☕🥐')
    await A.page.getByPlaceholder(/restaurant/i).fill('Fincan'); await A.page.waitForTimeout(1500)
    await L.shot(A.page, '15-composer-picker')
    await A.page.getByRole('option', { name: /Fincan Coffee/ }).click(); await A.page.waitForTimeout(500)
    await L.shot(A.page, '15-composer-ready')
    const t1 = Date.now()
    await A.page.getByRole('button', { name: 'Post', exact: true }).click()
    await A.page.waitForURL(L.CONSUMER + '/', { timeout: 30000 })
    L.log('post -> home ms', Date.now() - t1)
    await A.page.waitForTimeout(2500)
    await L.shot(A.page, '15-after-post')
    L.log('tab selected:', await A.page.evaluate(() => document.querySelector('[role=tab][aria-selected=true]')?.innerText))
    L.log('first cards:', (await A.page.evaluate(() => [...document.querySelectorAll('article')].slice(0, 3).map(a => a.innerText.replace(/\n+/g, ' | ').slice(0, 160)))))
    const posts = await api.get('posts?select=id,caption,restaurant_id,photo_path,is_verified,visit_id,created_at&user_id=eq.' + api.uid + '&order=created_at.desc&limit=1')
    L.log('db post:', JSON.stringify(posts))
  })
  L.log('errors', A.errors)
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
