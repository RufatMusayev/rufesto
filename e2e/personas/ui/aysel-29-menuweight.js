const L = require('./aysel-lib')
;(async () => {
  const b = await L.launch()
  const A = await L.phone(b, 'Aysel Məmmədova')
  const cdp = await A.ctx.newCDPSession(A.page)
  await cdp.send('Network.enable')
  const reqs = new Map()
  cdp.on('Network.requestWillBeSent', e => reqs.set(e.requestId, { url: e.request.url, type: e.type, bytes: 0 }))
  cdp.on('Network.loadingFinished', e => { const r = reqs.get(e.requestId); if (r) r.bytes = e.encodedDataLength })
  await A.page.goto(L.CONSUMER + '/restaurant/fincan-coffee'); await A.page.waitForTimeout(3000)
  for (let i = 0; i < 14; i++) { await A.page.evaluate(() => window.scrollBy(0, 700)); await A.page.waitForTimeout(500) }
  await A.page.waitForTimeout(2500)
  const imgs = [...reqs.values()].filter(r => r.type === 'Image')
  const kb = n => Math.round(n / 1024)
  L.log('Fincan menu fully scrolled: images', imgs.length, 'total', kb(imgs.reduce((s, r) => s + r.bytes, 0)), 'KB; avg', kb(imgs.reduce((s, r) => s + r.bytes, 0) / imgs.length), 'KB; max', kb(Math.max(...imgs.map(r => r.bytes))), 'KB')
  const dims = await A.page.evaluate(() => [...document.querySelectorAll('.ig-grid-tile img')].map(i => i.naturalWidth + 'x' + i.naturalHeight + ' shown ' + Math.round(i.getBoundingClientRect().width) + 'x' + Math.round(i.getBoundingClientRect().height)).slice(0, 4))
  L.log('tile image dims', dims.join(' | '))
  L.log('example urls', imgs.slice(0, 3).map(r => r.url.replace(/^https?:\/\//, '').slice(0, 100)).join(' | '))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
