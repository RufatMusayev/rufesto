const L = require('./aysel-r3-lib')
const sleep = ms => new Promise(r => setTimeout(r, ms))
;(async () => {
  const b = await L.launch()
  const F = await L.phone(b, 'Mehriban Rzayeva')
  await F.page.route('**/rpc/send_friend_request', r => r.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ message: 'boom' }) }))
  await F.page.goto(L.CONSUMER + '/explore'); await sleep(2500)
  await F.page.getByPlaceholder(/Dishes, places, people/i).fill('aysel'); await sleep(3000)
  const btn = F.page.getByRole('button', { name: /Add friend/i }).first()
  await btn.click()
  await sleep(150); L.log('150 ms after tap:', await F.page.evaluate(() => [...document.querySelectorAll('button')].filter(b => /Add friend|Requested/.test(b.innerText)).map(b => b.innerText.trim()).slice(0, 3)))
  await sleep(2500); L.log('2.6 s after tap (server said 500):', await F.page.evaluate(() => [...document.querySelectorAll('button')].filter(b => /Add friend|Requested/.test(b.innerText)).map(b => b.innerText.trim()).slice(0, 3)), '| toast/alert:', await F.page.evaluate(() => [...document.querySelectorAll('[role=status],[role=alert],.toast')].map(e => e.innerText.trim()).join(' / ')))
  await L.shot(F.page, '08c-rollback')
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
