'use strict'
// Turns the time segments of a sim run (.sim-segments.json) into the SQL that moves each block to its intended time of day.
//   node personas/shift-sql.js <template.sql> [segments.json] > out.sql
// The template has a `__SEGMENTS__` placeholder that becomes the rows of
//   INSERT INTO _seg (n, t0, t1, shift) VALUES __SEGMENTS__;
// one per segment: (n, 't0'::timestamptz, 't1'::timestamptz, interval '<seconds> seconds'), shift = t0 - target. A segment whose
// target is not at least 10 minutes in the past (day 0 run before that time of day) gets shift 0 and is left where it is.
const fs = require('fs')
const path = require('path')

const MIN_SHIFT_S = 600
const [templateFile, segmentsArg] = process.argv.slice(2)
if (!templateFile) { console.error('usage: node personas/shift-sql.js <template.sql> [segments.json] > out.sql'); process.exit(2) }

const file = segmentsArg || path.join(__dirname, '.sim-segments.json')
let data
try { data = JSON.parse(fs.readFileSync(file, 'utf8')) } catch (e) { console.error(`cannot read ${file}: ${e.message}`); process.exit(1) }
const template = fs.readFileSync(templateFile, 'utf8')
const PLACEHOLDER = /^__SEGMENTS__(?=;)/m      // the line of the INSERT (the template's header comment mentions the name too)
if (!PLACEHOLDER.test(template)) { console.error('the template has no line "__SEGMENTS__;"'); process.exit(1) }

const rows = []
let shifted = 0, maxShift = 0
for (const s of data.segments || []) {
  const t0 = Date.parse(s.t0), t1 = Date.parse(s.t1), target = Date.parse(s.target)
  if ([t0, t1, target].some(Number.isNaN)) { console.error(`segment ${s.n}: bad time`); process.exit(1) }
  let seconds = Math.round((t0 - target) / 1000)
  if (seconds < MIN_SHIFT_S) seconds = 0
  if (seconds) { shifted++; maxShift = Math.max(maxShift, seconds) }
  const label = String(s.label || '').replace(/[\r\n]+/g, ' ')
  rows.push(`-- ${s.n} ${label}: target ${s.target}\n(${s.n}, '${s.t0}'::timestamptz, '${s.t1}'::timestamptz, interval '${seconds} seconds')`)
}
if (!rows.length) rows.push("(0, '1970-01-01T00:00:00Z'::timestamptz, '1970-01-01T00:00:00Z'::timestamptz, interval '0 seconds')")

const header = `-- generated by personas/shift-sql.js from ${path.basename(file)}: simulated date ${data.day}, ${data.daysBack} day(s) back, server clock skew ${data.serverSkewMs} ms, ${rows.length} segments\n`
process.stdout.write(header + template.replace(PLACEHOLDER, () => rows.join(',\n')))
console.error(`shift-sql: ${(data.segments || []).length} segments, ${shifted} to move (largest shift ${(maxShift / 3600).toFixed(1)} h)`)
