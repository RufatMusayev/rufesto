const L = require('./aysel-lib')
const step = async (n, fn) => { try { L.log('\n=== ' + n); await fn() } catch (e) { L.log('STEP FAILED', n, String(e.message).split('\n')[0]) } }
;(async () => {
  const b = await L.launch()
  const { page, errors } = await L.phone(b, 'Aysel Məmmədova')
  const a = await L.api('Aysel Məmmədova')
  await page.goto(L.CONSUMER + '/'); await page.waitForSelector('.soc-feed-slot'); await page.waitForTimeout(800)
  await page.getByRole('tab', { name: 'Discover', exact: true }).click()
  await page.waitForSelector('.dsc .dsc-rc'); await page.waitForTimeout(1200)

  await step('cuisine chip Italian', async () => {
    const t0 = Date.now()
    await page.getByRole('button', { name: 'Italian', exact: true }).click()
    await page.waitForTimeout(150)
    await page.waitForFunction(() => !document.querySelector('.dsc-skel, .dsc-skeleton'), null, { timeout: 10000 }).catch(() => {})
    await page.waitForTimeout(600)
    L.log('chip filter ms (approx)', Date.now() - t0)
    L.log(await page.evaluate(() => [...document.querySelectorAll('.dsc section')].map(s => (s.querySelector('h2')?.innerText || '?') + ': ' + [...s.querySelectorAll('h3')].map(h => h.innerText).join(', ')).join('\n')))
    await L.shot(page, '06-discover-italian-0')
    await page.evaluate(() => window.scrollBy(0, 900)); await page.waitForTimeout(500)
    await L.shot(page, '06-discover-italian-1')
    await page.getByRole('button', { name: 'All', exact: true }).first().click(); await page.waitForTimeout(800)
  })

  await step('follow a new place', async () => {
    const before = await a.get('user_follows?select=restaurant_id&user_id=eq.' + a.uid)
    L.log('follows before', before.length)
    await page.evaluate(() => window.scrollTo(0, 0)); await page.waitForTimeout(300)
    const btn = page.getByRole('button', { name: /Follow Meze Istanbul/ }).first()
    L.log('follow btn aria', await btn.getAttribute('aria-label'), 'box', JSON.stringify(await btn.boundingBox()))
    await btn.scrollIntoViewIfNeeded()
    const t0 = Date.now()
    await btn.click()
    await page.waitForFunction(() => [...document.querySelectorAll('button')].some(x => /Unfollow Meze Istanbul/.test(x.getAttribute('aria-label') || '')), null, { timeout: 8000 }).catch(() => L.log('did not flip to Following'))
    L.log('flip ms', Date.now() - t0)
    await page.waitForTimeout(800)
    await L.shot(page, '06-follow-done')
    const after = await a.get('user_follows?select=restaurant_id&user_id=eq.' + a.uid)
    L.log('follows after', after.length)
    L.log('same place elsewhere on page shows following?', await page.getByRole('button', { name: /Unfollow Meze Istanbul/ }).count(), 'follow still', await page.getByRole('button', { name: /^Follow Meze Istanbul/ }).count())
    // home: does followers count on cards update
    L.log(await page.evaluate(() => [...document.querySelectorAll('.dsc-rc')].filter(c => /Meze/.test(c.innerText)).map(c => c.innerText.replace(/\s+/g, ' ').slice(0, 80))))
  })

  await step('save a dish (trending Tiramisù)', async () => {
    await page.evaluate(() => window.scrollTo(0, 0)); await page.waitForTimeout(300)
    const dc = page.locator('.dsc-dc').filter({ hasText: 'Tiramisù' }).first()
    await dc.scrollIntoViewIfNeeded()
    const t0 = Date.now()
    await dc.locator('a').click()
    await page.waitForSelector('.sheet', { timeout: 15000 })
    L.log('sheet ms', Date.now() - t0)
    await page.waitForTimeout(800)
    L.log('sheet buttons', await page.evaluate(() => [...document.querySelectorAll('.sheet button, .sheet a')].map(b => (b.getAttribute('aria-label') || b.innerText || '').trim().slice(0, 40) + ' ' + Math.round(b.getBoundingClientRect().width) + 'x' + Math.round(b.getBoundingClientRect().height))))
    const save = page.locator('.sheet button[aria-label*="ave" i]').first()
    L.log('save btn count', await page.locator('.sheet button[aria-label*="ave" i]').count())
    const saved0 = await a.get('saved_dishes?select=dish_id&user_id=eq.' + a.uid)
    L.log('saved before', saved0.length)
    await save.click(); await page.waitForTimeout(1200)
    await L.shot(page, '06-dish-saved')
    const saved1 = await a.get('saved_dishes?select=dish_id&user_id=eq.' + a.uid)
    L.log('saved after', saved1.length)
    // like in sheet
    const like = page.locator('.sheet button[aria-label*="ike" i]').first()
    L.log('like btn', await like.getAttribute('aria-label'))
    // close and open Profile > saved
    await page.keyboard.press('Escape'); await page.waitForTimeout(500)
  })
  await step('profile saved tab', async () => {
    await page.goto(L.CONSUMER + '/profile'); await page.waitForTimeout(2500)
    await L.shot(page, '06-profile')
    L.log((await page.evaluate(() => document.body.innerText)).slice(0, 600))
    const saved = page.getByRole('tab', { name: /Saved/ }).or(page.getByRole('button', { name: /Saved/ })).first()
    if (await saved.count()) { await saved.click(); await page.waitForTimeout(1200); await L.shot(page, '06-profile-saved'); L.log((await page.evaluate(() => document.body.innerText)).slice(0, 500)) }
  })
  L.log('\nerrors', errors)
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
