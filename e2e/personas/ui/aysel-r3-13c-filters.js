const L = require('./aysel-r3-lib')
const sleep = ms => new Promise(r => setTimeout(r, ms))
;(async () => {
  const b = await L.launch()
  const A = await L.phone(b, 'Aysel Məmmədova')
  const page = A.page
  const note = (k, v) => L.log('  >>', k, v)
  await page.goto(L.CONSUMER + '/explore'); await sleep(2500)
  note('buttons at the top (not focused)', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('button')].slice(0, 4).map(b => (b.getAttribute('aria-label') || b.innerText || '(none)').trim().slice(0, 24) + ' ' + Math.round(b.getBoundingClientRect().width) + 'x' + Math.round(b.getBoundingClientRect().height) + ' top ' + Math.round(b.getBoundingClientRect().top)))))
  const fb = page.locator('button[aria-label]').filter({ hasText: /^$/ }).first()
  const label = await page.evaluate(() => { const b = [...document.querySelectorAll('button')].find(x => x.getBoundingClientRect().top < 80 && x.getBoundingClientRect().left > 330); return b ? b.getAttribute('aria-label') : null })
  note('filter button aria-label', label)
  await page.locator('button[aria-label="' + label + '"]').click(); await page.waitForSelector('.bs-panel'); await sleep(900)
  await L.shot(page, '13c-filters-sheet')
  note('sheet text', (await page.evaluate(() => document.querySelector('.bs-panel').innerText)).replace(/\n+/g, ' | ').slice(0, 380))
  note('sheet controls', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('.bs-panel button, .bs-panel [role=switch], .bs-panel input')].map(e => ((e.getAttribute('aria-label') || e.innerText || e.type || '').trim().replace(/\n+/g, ' ').slice(0, 16)) + ' ' + Math.round(e.getBoundingClientRect().height)).slice(0, 30))))
  const sheet = page.locator('.bs-panel')
  await sheet.getByText('Italian', { exact: true }).click()
  await sheet.getByRole('button', { name: /Show results/i }).click(); await sleep(3000)
  await L.shot(page, '13c-filter-italian')
  note('Italian: url', page.url().replace(L.CONSUMER, ''))
  note('Italian: text', (await page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 520))
  await page.locator('button[aria-label="' + label + '"]').click({ timeout: 4000 }).catch(() => note('filter button after applying', 'not clickable'))
  await page.waitForSelector('.bs-panel', { timeout: 4000 }).catch(() => {}); await sleep(600)
  const sw = page.locator('.bs-panel').getByRole('switch').or(page.locator('.bs-panel input[type=checkbox]')).first()
  await sw.click({ force: true }); await sleep(200)
  await page.locator('.bs-panel').getByRole('button', { name: /Show results/i }).click(); await sleep(3000)
  await L.shot(page, '13c-filter-open-italian')
  note('Italian + Open now (all closed): url', page.url().replace(L.CONSUMER, ''))
  note('text', (await page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 360))
  note('chips under the field', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('[class*=sr-] button')].map(b => (b.getAttribute('aria-label') || b.innerText || '').trim().slice(0, 30)).filter(Boolean).slice(0, 8))))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
