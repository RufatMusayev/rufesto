// Round 2, part 3: bill (default method, sticky bar, line prices, tip chips), demo card + tip to Ülviyyə, review prompt, receipt, visits.
const L = require('./aysel-r2-lib')
;(async () => {
  const b = await L.launch()
  const A = await L.phone(b, 'Aysel Məmmədova')
  const api = await L.api('Aysel Məmmədova')
  await A.page.goto(L.CONSUMER + '/table'); await A.page.waitForTimeout(2500)
  await L.step('table page after serve', async () => {
    await L.shot(A.page, '04-table-served')
    L.log('table text:', (await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 700))
    L.log('header wraps?', await A.page.evaluate(() => { const e = [...document.querySelectorAll('*')].find(x => x.children.length === 0 && /#T1/.test(x.textContent)); return e ? Math.round(e.getBoundingClientRect().height) + 'px high: ' + e.textContent.trim() : 'n/a' }))
    L.log('dish icons in order card:', await A.page.evaluate(() => [...document.querySelectorAll('.stagger-item img, .stagger-item [class*=emoji], .stagger-item [class*=thumb]')].slice(0, 4).map(e => e.tagName + ' ' + (e.alt || e.textContent.trim()))))
  })
  await L.step('bill page', async () => {
    await A.page.getByRole('button', { name: /View bill/i }).or(A.page.getByRole('link', { name: /View bill/i })).first().click(); await A.page.waitForTimeout(2500)
    await L.shot(A.page, '04-bill-0')
    L.log((await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 900))
    const probe = await A.page.evaluate(() => { const opts = [...document.querySelectorAll('button.bl-option')]; const card = opts.find(x => /Card/.test(x.innerText)); const bar = document.querySelector('.bl-paybar'); const r = card.getBoundingClientRect(), br = bar.getBoundingClientRect(); return { selected: opts.map(o => o.innerText.split('\n')[0].trim() + ':' + (o.getAttribute('aria-checked') || o.className.includes('on'))), cardRect: [Math.round(r.top), Math.round(r.bottom)], barTop: Math.round(br.top), covered: Math.max(0, Math.round(r.bottom - br.top)) } })
    L.log('payment options / overlap:', JSON.stringify(probe))
  })
  await L.step('card + 10% tip -> Ülviyyə -> pay', async () => {
    await A.page.evaluate(() => window.scrollBy(0, 300)); await A.page.waitForTimeout(300)
    await A.page.locator('button.bl-option').filter({ hasText: /Card/ }).click(); await A.page.waitForTimeout(600)
    L.log('tip chips:', await A.page.evaluate(() => [...document.querySelectorAll('button')].filter(b => /^(No tip|\d+%|Custom)/.test(b.innerText.trim())).map(b => b.innerText.trim().replace(/\n+/g, ' '))))
    await A.page.locator('button').filter({ hasText: /^10%/ }).first().click(); await A.page.waitForTimeout(600)
    await L.shot(A.page, '04-tip-chosen')
    L.log('tip block:', (await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').match(/ADD A TIP.*?PAYMENT METHOD/i)?.[0])
    await A.page.locator('button').filter({ hasText: /Ülviyyə/ }).first().click().catch(() => {}); await A.page.waitForTimeout(300)
    await A.page.getByRole('button', { name: /^Pay /i }).first().click(); await A.page.waitForTimeout(900)
    await L.shot(A.page, '04-card-sheet')
    const t0 = Date.now()
    await A.page.getByRole('button', { name: /\(demo\)/ }).click()
    await A.page.waitForFunction(() => /Payment received|Bill settled|Settled/i.test(document.body.innerText), null, { timeout: 25000 }).catch(() => L.log('no settled text'))
    L.log('payment ms', Date.now() - t0)
    await A.page.waitForTimeout(1500)
    await A.page.evaluate(() => window.scrollTo(0, 0)); await A.page.waitForTimeout(300)
    await L.shot(A.page, '04-paid-top')
    await A.page.evaluate(() => window.scrollTo(0, document.body.scrollHeight)); await A.page.waitForTimeout(400)
    await L.shot(A.page, '04-paid-review-prompt')
    L.log('after pay:', (await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 800))
    L.log('review rows geometry:', await A.page.evaluate(() => [...document.querySelectorAll('button')].filter(b => /Rate .*: 1 of 5/.test(b.getAttribute('aria-label') || '')).map(b => (b.getAttribute('aria-label') || '') + ' left=' + Math.round(b.getBoundingClientRect().left) + ' top=' + Math.round(b.getBoundingClientRect().top))))
  })
  await L.step('reload /bill after paying', async () => {
    await A.page.goto(L.CONSUMER + '/bill'); await A.page.waitForTimeout(3000)
    await L.shot(A.page, '04-bill-after-reload')
    L.log('/bill after pay:', (await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 500))
  })
  L.log('errors', A.errors.filter(e => !/ERR_ABORTED/.test(e)))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
