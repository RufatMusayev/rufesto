const L = require('./aysel-r2-lib')
;(async () => {
  const b = await L.launch()
  const A = await L.phone(b, 'Aysel Məmmədova')
  const api = await L.api('Aysel Məmmədova')
  const M = await L.desk(b, 'Səid Əhmədov')
  await M.page.goto(L.RESTO + '/bookings'); await M.page.waitForTimeout(3500)
  L.log('manager bell:', await M.page.evaluate(() => [...document.querySelectorAll('[aria-label*="otification" i]')].map(e => e.getAttribute('aria-label')).slice(0, 1)))
  const btn = M.page.getByRole('button', { name: 'Confirm', exact: true })
  L.log('Confirm buttons:', await btn.count())
  await btn.first().click(); await M.page.waitForTimeout(2000)
  await L.shot(M.page, '15c-mgr-after-confirm')
  L.log('mgr page after:', (await M.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(150, 520))
  const bk = await api.rpc('list_my_bookings')
  L.log('my bookings:', JSON.stringify((bk || []).slice(0, 2).map(x => [x.status, x.restaurant_name, x.starts_at])))
  // Aysel's bell/inbox
  await A.page.goto(L.CONSUMER + '/'); await A.page.waitForSelector('.soc-feed-slot article'); await A.page.waitForTimeout(3000)
  L.log('bell:', await A.page.evaluate(() => { const e = document.querySelector('a[href="/notifications"], button[aria-label*="otification" i]'); return e ? e.innerText.trim() : null }))
  await A.page.goto(L.CONSUMER + '/notifications'); await A.page.waitForSelector('li.ntf-li'); await A.page.waitForTimeout(1500)
  L.log('top 3:', await A.page.evaluate(() => [...document.querySelectorAll('li.ntf-li')].slice(0, 3).map(li => li.innerText.replace(/\n+/g, ' | '))))
  await L.shot(A.page, '15c-inbox-after-confirm')
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
