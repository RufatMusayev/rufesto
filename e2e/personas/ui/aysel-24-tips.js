const L = require('./aysel-lib')
;(async () => {
  const b = await L.launch()
  const W = await L.desk(b, 'Ülviyyə Kazımova')
  await W.page.goto(L.RESTO + '/waiter'); await W.page.waitForTimeout(3500)
  L.log('waiter page tips:', (await W.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 400))
  await W.page.goto(L.RESTO + '/my-tips'); await W.page.waitForTimeout(3500)
  await L.shot(W.page, '24-my-tips')
  L.log('my-tips:', (await W.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 700))
  const M = await L.desk(b, 'Səid Əhmədov')
  await M.page.goto(L.RESTO + '/bills'); await M.page.waitForTimeout(3500)
  await L.shot(M.page, '24-bills')
  L.log('bills:', (await M.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 700))
  await M.page.goto(L.RESTO + '/'); await M.page.waitForTimeout(3500)
  await L.shot(M.page, '24-overview')
  L.log('overview:', (await M.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 600))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
