const L = require('./aysel-r2-lib')
;(async () => {
  const b = await L.launch()
  const A = await L.phone(b, 'Aysel Məmmədova')
  const t0 = Date.now()
  await A.page.goto(L.CONSUMER + '/'); await A.page.waitForSelector('.soc-feed-slot article', { timeout: 40000 })
  L.log('first card ms', Date.now() - t0)
  await A.page.waitForTimeout(1500)
  await L.shot(A.page, '00-home-top')
  L.log('bell/aria:', await A.page.evaluate(() => [...document.querySelectorAll('a[href="/notifications"], button[aria-label*="otification" i]')].map(e => (e.getAttribute('aria-label') || '') + ' | ' + e.innerText.trim())))
  L.log((await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 900))
  L.log('errors', A.errors)
  const api = await L.api('Aysel Məmmədova')
  const fr = await api.rpc('my_friends'); L.log('friends', JSON.stringify(Array.isArray(fr) ? fr.map(f => f.name) : fr))
  const nb = await api.rpc('notifications_badge'); L.log('badge', JSON.stringify(nb))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
