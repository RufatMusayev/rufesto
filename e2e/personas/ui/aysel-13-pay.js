const L = require('./aysel-lib')
const step = async (n, fn) => { try { L.log('\n=== ' + n); await fn() } catch (e) { L.log('STEP FAILED', n, String(e.message).split('\n')[0]) } }
;(async () => {
  const b = await L.launch()
  const A = await L.phone(b, 'Aysel Məmmədova')
  await A.page.goto(L.CONSUMER + '/bill'); await A.page.waitForTimeout(2500)
  await step('pick card + 10% tip, who gets it, pay', async () => {
    await A.page.evaluate(() => window.scrollBy(0, 300)); await A.page.waitForTimeout(300)
    await A.page.locator('button.bl-option').nth(1).click({ timeout: 8000 }); await A.page.waitForTimeout(500)
    await A.page.locator('button').filter({ hasText: /^10%/ }).first().click({ timeout: 8000 }); await A.page.waitForTimeout(600)
    await L.shot(A.page, '13-tip-recipient')
    L.log('recipient default pressed?', await A.page.evaluate(() => [...document.querySelectorAll('button')].filter(b => /Ülviyyə|Whole team/.test(b.innerText)).map(b => b.innerText.replace(/\n+/g, ' ') + ' pressed=' + b.getAttribute('aria-pressed') + ' checked=' + b.getAttribute('aria-checked') + ' cls=' + b.className)))
    await A.page.locator('button').filter({ hasText: /Ülviyyə/ }).first().click(); await A.page.waitForTimeout(400)
    await A.page.getByRole('button', { name: /^Pay ₼13\.59$/ }).click(); await A.page.waitForTimeout(1000)
    await L.shot(A.page, '13-card-sheet')
    const t0 = Date.now()
    await A.page.getByRole('button', { name: /Pay ₼13\.59 \(demo\)/ }).click()
    await A.page.waitForFunction(() => /Receipt|Thank|paid|Paid|Settled/i.test(document.body.innerText), null, { timeout: 25000 }).catch(() => L.log('no success text'))
    L.log('payment ms', Date.now() - t0)
    await A.page.waitForTimeout(1500)
    await L.shot(A.page, '13-paid')
    L.log('after pay:', (await A.page.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(0, 900))
    L.log('URL', A.page.url().replace(L.CONSUMER, ''))
    L.log('buttons', await A.page.evaluate(() => [...document.querySelectorAll('button,a')].filter(e => e.offsetParent).map(e => ((e.innerText || e.getAttribute('aria-label') || '').trim().replace(/\n+/g, ' ').slice(0, 40)) + ' h=' + Math.round(e.getBoundingClientRect().height)).filter(Boolean)))
  })
  L.log('errors', A.errors)
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
